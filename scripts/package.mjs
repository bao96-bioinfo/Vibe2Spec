import {mkdir, readFile, writeFile, readdir, cp, rm, lstat, mkdtemp, rename} from 'node:fs/promises';
import {resolve, dirname, join, relative, sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const marker='.vibe2spec-generated', inventory='.vibe2spec-files.json';
const ownership='Generated by scripts/package.mjs; edit the source files.\n';
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
async function noSymbolicAncestors(path) {
 let current=resolve(path);
 for(;;){
  try {const info=await lstat(current);if(info.isSymbolicLink())throw new Error('Assembly paths must not contain symbolic links.');}
  catch(error){if(error.code!=='ENOENT')throw error;}
  const parent=dirname(current);if(parent===current)break;current=parent;
 }
}
async function inspect(directory) {
 const entries=[];
 async function visit(current){
  for(const entry of await readdir(current,{withFileTypes:true})){
   const file=join(current,entry.name),info=await lstat(file);
   if(info.isSymbolicLink()||(!info.isDirectory()&&!info.isFile()))throw new Error('Generated package contents must be regular files and directories.');
   const entryPath=relative(directory,file).split(sep).join('/');
   if(info.isDirectory()){entries.push({path:entryPath,kind:'directory'});await visit(file);}
   else if(entryPath!==inventory)entries.push({path:entryPath,kind:'file',sha256:sha(await readFile(file))});
  }
 }
 await visit(directory);return entries.sort((a,b)=>Buffer.compare(Buffer.from(a.path),Buffer.from(b.path)));
}
async function resolveDocumentationLinks(stage) {
 const repository='https://github.com/bao96-bioinfo/Vibe2Spec/blob/main/';
 async function visit(directory) {
  for(const entry of await readdir(directory,{withFileTypes:true})) {
   const file=join(directory,entry.name);
   if(entry.isDirectory()){await visit(file);continue;}
   if(!entry.name.endsWith('.md'))continue;
   const original=await readFile(file,'utf8');
   const replacements=new Map();
   for(const match of original.matchAll(/\[[^\]]+\]\(([^)]+)\)/g)) {
    const target=match[1];
    if(/^[a-z]+:|^#/i.test(target))continue;
    const hashAt=target.indexOf('#');
    const pathname=hashAt<0?target:target.slice(0,hashAt);
    const fragment=hashAt<0?'':target.slice(hashAt);
    const destination=resolve(dirname(file),pathname);
    const packagedPath=relative(stage,destination);
    if(packagedPath==='..'||packagedPath.startsWith(`..${sep}`)||resolve(stage,packagedPath)!==destination)throw new Error('A packaged documentation link leaves the package.');
    try{await lstat(destination);continue;}catch(error){if(error.code!=='ENOENT')throw error;}
    const source=resolve(root,packagedPath);
    const sourceInfo=await lstat(source);
    if(!sourceInfo.isFile()&&!sourceInfo.isDirectory())throw new Error('A documentation link targets an unsupported source artifact.');
    // Development evidence remains in the repository. Runtime guidance and
    // templates stay local; the installed package never needs authoring tools.
    const url=repository+packagedPath.split(sep).map(encodeURIComponent).join('/')+fragment;
    replacements.set(target,url);
   }
   if(replacements.size)await writeFile(file,original.replace(/(\[[^\]]+\]\()([^)]+)(\))/g,(match,start,target,end)=>replacements.has(target)?start+replacements.get(target)+end:match));
  }
 }
 await visit(join(stage,'docs'));
}
export async function assemble(destination=join(root,'plugins/vibe2spec')) {
 const output=resolve(destination);
 if(output===root || !output.endsWith('/vibe2spec')) throw new Error('Assembly output must be a dedicated vibe2spec directory.');
 await noSymbolicAncestors(output);
 await mkdir(dirname(output),{recursive:true});
 let existing=null;
 try{existing=await readdir(output);}catch(error){if(error.code!=='ENOENT')throw error;}
 if(existing?.length&&(!existing.includes(marker)||await readFile(join(output,marker),'utf8')!==ownership))throw new Error('Refusing to replace a directory without the exact assembly ownership marker.');
 const stage=await mkdtemp(`${output}.stage-`);
 let backup=null,published=false;
 try {
 await writeFile(join(stage,marker),ownership);
 for(const name of ['skills','templates','docs','assets','LICENSE']) await cp(join(root,name),join(stage,name),{recursive:true});
 await mkdir(join(stage,'scripts'),{recursive:true});
 for(const name of await readdir(join(root,'scripts'))) if(name.endsWith('.mjs') && !['package.mjs','host-smoke.mjs'].includes(name)) await cp(join(root,'scripts',name),join(stage,'scripts',name));
 const pkg=JSON.parse(await readFile(join(root,'package.json'),'utf8'));
 await writeFile(join(stage,'package.json'),JSON.stringify({name:pkg.name,version:pkg.version,type:'module',engines:pkg.engines,private:true},null,2)+'\n');
 for(const host of ['claude','codex']) {
  await mkdir(join(stage,`.${host}-plugin`),{recursive:true});
  await cp(join(root,`packaging/${host}/plugin.json`),join(stage,`.${host}-plugin/plugin.json`));
 }
 const manifest=JSON.parse(await readFile(join(root,'packaging/codex/plugin.json'),'utf8'));
 const {skills,interface:ui,...identity}=manifest;
 const portable={$schema:'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json',...identity,extensions:{'com.openai':{interface:ui}}};
 await writeFile(join(stage,'plugin.json'),JSON.stringify(portable,null,2)+'\n');
 await inspect(stage);
 await resolveDocumentationLinks(stage);
 const next=await inspect(stage);
 await writeFile(join(stage,inventory),JSON.stringify({inventory_version:1,files:next},null,2)+'\n');
 if(existing?.length){
  const actual=await inspect(output);
  if(existing.includes(inventory)){
   const saved=JSON.parse(await readFile(join(output,inventory),'utf8'));
   if(saved.inventory_version!==1||JSON.stringify(saved.files)!==JSON.stringify(actual))throw new Error('Refusing to replace modified or unowned package contents.');
  }else{
   // Migrate only this repository's initial generated package. Other destinations
   // must have the inventory created by this assembler, even if they copy a marker.
   const expectedPaths=new Set(next.map(item=>item.path));
   if(output!==join(root,'plugins/vibe2spec')||actual.some(item=>!expectedPaths.has(item.path)))throw new Error('Refusing to replace package contents without an ownership inventory.');
  }
 }
 // Copying and validation finish before the previous package is touched.
 await noSymbolicAncestors(output);
 if(existing!==null){backup=await mkdtemp(`${output}.previous-`);await rename(output,join(backup,'package'));}
 try{await rename(stage,output);published=true;}catch(error){if(backup)await rename(join(backup,'package'),output);throw error;}
 if(backup)await rm(backup,{recursive:true,force:true});
 return output;
 } finally {if(!published)await rm(stage,{recursive:true,force:true});}
}
if(process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) console.log(await assemble(process.argv[2]));
